CREATE FUNCTION workspace_intent_authorized(pr BIGINT) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
 SELECT EXISTS (SELECT 1 FROM build_intents b JOIN pull_requests p ON p.id=b.pull_request_id
 JOIN repos r ON r.id=p.repo_id JOIN installations i ON i.id=r.installation_id
 JOIN workspaces w ON w.id=i.workspace_id AND w.state='active'
 WHERE p.id=pr AND b.workspace_id=w.id AND (b.source='automatic' OR
 (b.authorization_stamp IS NOT NULL AND b.authorization_stamp=workspace_authorization_stamp(r.id,b.requested_by))));
$$;
-- Once the route fence accepts a candidate, it belongs to the workspace. Actor
-- departure must not interrupt route recovery or final build accounting.
CREATE FUNCTION workspace_request_published(pr BIGINT) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
 SELECT EXISTS (SELECT 1 FROM build_intents b JOIN pull_requests p ON p.id=b.pull_request_id
 JOIN repos r ON r.id=p.repo_id AND r.accessible
 JOIN installations i ON i.id=r.installation_id AND i.status='active'
 JOIN workspaces w ON w.id=i.workspace_id AND w.state='active'
 JOIN environment_routes route ON route.pull_request_id=p.id AND route.state='active'
 WHERE p.id=pr AND b.workspace_id=w.id AND b.generation=p.generation
 AND route.generation=b.generation AND route.revision=b.revision);
$$;
CREATE FUNCTION workspace_publication_authorized(pr BIGINT) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
 SELECT workspace_intent_authorized(pr) OR workspace_request_published(pr);
$$;
