-- DB functions share authorization predicates across feature-owned queries.
-- They are invoker-security, parameterized, and never trust session selection.
-- +goose StatementBegin
CREATE FUNCTION workspace_repository_access(repo BIGINT, actor BIGINT, ability TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
 SELECT EXISTS (
  SELECT 1 FROM repos r JOIN installations i ON i.id = r.installation_id
  JOIN workspaces w ON w.id = i.workspace_id AND w.state = 'active'
  JOIN workspace_memberships m ON m.workspace_id = w.id AND m.user_id = actor AND m.state = 'active'
  WHERE r.id = repo AND (
   m.role IN ('owner', 'admin') OR
   (EXISTS (SELECT 1 FROM repository_memberships g WHERE g.repo_id = r.id AND g.workspace_id = w.id AND g.user_id = actor)
    AND (ability IN ('read', 'preview') OR (ability = 'operate' AND m.role = 'developer')))
  ) AND ability IN ('read', 'preview', 'operate', 'manage')
 );
$$;
CREATE FUNCTION workspace_installation_access(installation BIGINT, actor BIGINT, ability TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
 SELECT EXISTS (SELECT 1 FROM installations i JOIN workspaces w ON w.id = i.workspace_id AND w.state = 'active'
 JOIN workspace_memberships m ON m.workspace_id = w.id AND m.user_id = actor AND m.state = 'active'
 WHERE i.id = installation AND (m.role IN ('owner', 'admin') OR
 (ability = 'read' AND EXISTS (SELECT 1 FROM repos r WHERE r.installation_id = i.id AND workspace_repository_access(r.id, actor, 'read')))));
$$;
CREATE FUNCTION workspace_authorization_stamp(repo BIGINT, actor BIGINT) RETURNS TEXT
LANGUAGE sql STABLE AS $$
 SELECT m.revision::text || ':' || coalesce(g.revision, 0)::text
 FROM repos r JOIN installations i ON i.id = r.installation_id
 JOIN workspaces w ON w.id = i.workspace_id AND w.state = 'active'
 JOIN workspace_memberships m ON m.workspace_id = w.id AND m.user_id = actor AND m.state = 'active'
 LEFT JOIN repository_memberships g ON g.repo_id = r.id AND g.workspace_id = w.id AND g.user_id = actor
 WHERE r.id = repo AND workspace_repository_access(repo, actor, 'operate');
$$;
CREATE FUNCTION workspace_default(actor BIGINT) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE result BIGINT;
BEGIN
 PERFORM id FROM users WHERE id = actor FOR UPDATE;
 SELECT w.id INTO result FROM workspace_preferences p JOIN workspaces w ON w.id = p.workspace_id
 JOIN workspace_memberships m ON m.workspace_id = w.id AND m.user_id = actor AND m.state = 'active'
 WHERE p.user_id = actor AND w.state = 'active' AND m.role IN ('owner','admin');
 IF result IS NULL THEN
  INSERT INTO workspaces(name, owner_user_id, legacy_user_id)
  SELECT username || '''s workspace', id,CASE WHEN EXISTS(SELECT 1 FROM workspaces WHERE legacy_user_id=actor) THEN NULL ELSE actor END
  FROM users WHERE id = actor RETURNING id INTO result;
  INSERT INTO workspace_memberships(workspace_id,user_id,role) VALUES(result,actor,'owner');
  INSERT INTO workspace_preferences(user_id,workspace_id) VALUES(actor,result)
    ON CONFLICT(user_id) DO UPDATE SET workspace_id=EXCLUDED.workspace_id;
 END IF;
 RETURN result;
END; $$;
CREATE FUNCTION workspace_bind_installation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.workspace_id IS NULL AND NEW.owner_user_id IS NOT NULL THEN NEW.workspace_id := workspace_default(NEW.owner_user_id); END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER workspace_bind_installation BEFORE INSERT OR UPDATE OF owner_user_id ON installations
FOR EACH ROW EXECUTE FUNCTION workspace_bind_installation();
CREATE FUNCTION workspace_check_owner() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE wid BIGINT;
BEGIN
 IF TG_TABLE_NAME = 'workspaces' THEN wid := NEW.id; ELSE wid := coalesce(NEW.workspace_id,OLD.workspace_id); END IF;
 IF EXISTS (SELECT 1 FROM workspaces w WHERE w.id=wid AND w.state='active' AND NOT EXISTS
  (SELECT 1 FROM workspace_memberships m WHERE m.workspace_id=w.id AND m.user_id=w.owner_user_id AND m.role='owner' AND m.state='active')) THEN
  RAISE EXCEPTION 'active workspace requires its owner membership' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER workspace_owner_valid AFTER INSERT OR UPDATE ON workspaces
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION workspace_check_owner();
CREATE CONSTRAINT TRIGGER workspace_membership_owner_valid AFTER INSERT OR UPDATE OR DELETE ON workspace_memberships
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION workspace_check_owner();
CREATE FUNCTION workspace_check_repository_grant() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM repos r JOIN installations i ON i.id=r.installation_id WHERE r.id=NEW.repo_id AND i.workspace_id=NEW.workspace_id) THEN
  RAISE EXCEPTION 'repository grant crosses workspace' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END; $$;
