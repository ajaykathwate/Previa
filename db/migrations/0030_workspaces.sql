CREATE FUNCTION workspace_capture_intent() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE repo BIGINT;
BEGIN
 SELECT p.repo_id,i.workspace_id INTO repo,NEW.workspace_id FROM pull_requests p JOIN repos r ON r.id=p.repo_id JOIN installations i ON i.id=r.installation_id WHERE p.id=NEW.pull_request_id;
