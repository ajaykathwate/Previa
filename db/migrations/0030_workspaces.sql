CREATE TABLE workspaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    owner_user_id BIGINT NOT NULL REFERENCES users(id),
    legacy_user_id BIGINT UNIQUE REFERENCES users(id),
    state TEXT NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'deleting', 'deleted')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE workspace_memberships (
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    role TEXT NOT NULL CHECK (role IN ('owner', 'admin', 'developer', 'reviewer')),
    state TEXT NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'removed')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    removed_at TIMESTAMPTZ,
    PRIMARY KEY (workspace_id, user_id)
);
CREATE UNIQUE INDEX workspace_one_owner ON workspace_memberships(workspace_id)
    WHERE role = 'owner' AND state = 'active';
CREATE INDEX workspace_memberships_user ON workspace_memberships(user_id, workspace_id) WHERE state = 'active';
CREATE TABLE workspace_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    workspace_id BIGINT REFERENCES workspaces(id) ON DELETE SET NULL
);
